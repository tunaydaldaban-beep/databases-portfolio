"""Run verified Task 6/7 queries; save real timings and independent checks."""
import csv, sqlite3, time, platform
from collections import defaultdict
from pathlib import Path
here = Path(__file__).parent
con = sqlite3.connect(here / "telemetry.db")
report = ["# Execution evidence", "", "Generated by analyze.py; Python and SQLite versions are recorded below.",
          f"Python: {platform.python_version()}; SQLite: {sqlite3.sqlite_version}",
          f"Database size: {(here / 'telemetry.db').stat().st_size:,} bytes",
          f"Total rows: {con.execute('SELECT COUNT(*) FROM readings').fetchone()[0]:,}"]
queries = [
 ("Readings per machine", "SELECT machine, COUNT(*) AS n FROM readings GROUP BY machine", ()),
 ("Peak vibration (mm/s)", "SELECT machine, MAX(vib_rms) AS peak_vib FROM readings GROUP BY machine", ()),
 ("Readings above 2.0 mm/s", "SELECT COUNT(*) AS alarms FROM readings WHERE vib_rms > ?", (2.0,)),
 ("Average spindle load strictly after 18:00", "SELECT machine, AVG(spindle_load) AS avg_load FROM readings WHERE time(ts) > ? GROUP BY machine ORDER BY avg_load DESC", ("18:00:00",)),
]
results=[]
for title, sql, params in queries:
    start=time.perf_counter(); cur=con.execute(sql,params); rows=cur.fetchall(); ms=(time.perf_counter()-start)*1000
    results.append(rows)
    report += ["", "## "+title, "```sql", sql, "```", f"Bound parameters: {params!r}", f"Wall-clock time (single run): {ms:.3f} ms", "```", str([col[0] for col in cur.description]), *map(str,rows), "```"]
plan=con.execute('EXPLAIN QUERY PLAN '+queries[-1][1], queries[-1][2]).fetchall()
report += ["", "## Query plan", "```", *map(str,plan), "```", "SCAN readings is a full-table scan. Temporary B-trees may support GROUP BY and ORDER BY.", "Timings depend on cache, hardware and engine version; these are not a cloud benchmark."]
counts=defaultdict(int); peaks=defaultdict(float); sums=defaultdict(float); ns=defaultdict(int); alarms=0
with (here/'telemetry.csv').open(newline='') as f:
    for r in csv.DictReader(f):
        k=r['machine']; v=float(r['vib_rms']); counts[k]+=1; peaks[k]=max(peaks[k],v); alarms+=v>2.0
        if r['ts'].split(' ')[1] > '18:00:00': sums[k]+=float(r['spindle_load']); ns[k]+=1
assert dict(results[0])==dict(counts)
assert dict(results[1])==dict(peaks)
assert results[2][0][0]==alarms
assert all(abs(avg-sums[k]/ns[k])<1e-9 for k,avg in results[3])
con.execute('CREATE TEMP TABLE boundary(ts TEXT)')
con.executemany('INSERT INTO boundary VALUES (?)',[(s,) for s in ['2026-01-05 17:59:59','2026-01-05 18:00:00','2026-01-05 18:00:01','2026-01-06 00:00:00','2026-01-06 05:59:59','2026-01-06 06:00:00','2026-01-18 12:00:00']])
selected=[r[0] for r in con.execute('SELECT ts FROM boundary WHERE time(ts) > ?',('18:00:00',))]
assert selected==['2026-01-05 18:00:01']
wrong=[r[0] for r in con.execute("SELECT ts FROM boundary WHERE ts LIKE '%18%'")]
assert '2026-01-18 12:00:00' in wrong
report += ["", "## Independent verification", "PASS: CSV/Python counts, maxima, alarm count and means match SQL.", "PASS: strict time boundary includes 18:00:01, excludes 18:00:00 and early morning.", "PASS: deliberately broken LIKE '%18%' includes January 18 at noon, which is not an evening reading.", "", "This assumes 'after 18:00' means strictly 18:00:00–23:59:59 every day. A whole night shift (18:00–06:00) needs a different predicate."]
(here/'query-results.md').write_text('\n'.join(report)+'\n')
con.close()
print('Verified all three Task 6 results, Task 7 average, and boundary counterexample. See query-results.md.')
